using MongoDB.Driver;
using FacturaFlow.Api.Options;
using FacturaFlow.Api.Repositories;
using FacturaFlow.Api.Services;
using Microsoft.Extensions.Options;

var builder = WebApplication.CreateBuilder(args);
builder.Services.Configure<MongoOptions>(builder.Configuration.GetSection("Mongo"));
builder.Services.Configure<EmailOptions>(builder.Configuration.GetSection("Email"));
builder.Services.AddSingleton<IMongoClient>(sp => new MongoDB.Driver.MongoClient(sp.GetRequiredService<IOptions<MongoOptions>>().Value.ConnectionString));
builder.Services.AddSingleton<IFacturaRepository, MongoFacturaRepository>();
builder.Services.AddSingleton<IEmailSender, SmtpEmailSender>();
builder.Services.AddScoped<IReminderService, ReminderService>();
builder.Services.AddControllers();
builder.Services.AddEndpointsApiExplorer();
builder.Services.AddSwaggerGen();
builder.Services.AddCors(options => options.AddPolicy("frontend", policy => policy.WithOrigins(builder.Configuration["FrontendOrigin"] ?? "http://localhost:4200").AllowAnyHeader().AllowAnyMethod()));
var app = builder.Build();
app.UseSwagger(); app.UseSwaggerUI(); app.UseCors("frontend"); app.MapControllers();
app.MapGet("/health", () => Results.Ok(new { status = "ok", application = "FacturaFlow" }));
app.Run();
